//! Shared game math: `m_lib.c` helpers, libultra `sins`/`coss`, and the
//! `atans_table` angle lookup (`sys_math_atan.c`).
//!
//! Source-verified against ac-decomp `src/game/m_lib.c`,
//! `src/static/libultra/gu/{sins,coss}.c`, `src/system/sys_math_atan.c`
//! (primary) and the ACGC-PC-Port copies (secondary). `sins.c` and
//! `sys_math_atan.c` are byte-identical in both trees. `m_lib.c` differs
//! on PC: `add_calc` scales `fraction` / steps by `dt_num_60fps_frames`
//! (see `add_calc_dt`); everything else here matches retail.
//!
//! Angles are the N64/GC "short" format: 0x10000 = 360 degrees, stored as
//! `s16` (`i16`), wrapping arithmetic everywhere.
//!
//! The lookup tables live in `game_math_tables.rs`, generated by
//! `tools/gen_trig_tables.py` straight from the C tables.

use crate::game_math_tables::{ATNTABLE, SINTABLE};

/// `F32_IS_ZERO(v)`: `fabsf(v) < 0.008f` (include/types.h).
pub fn f32_is_zero(v: f32) -> bool {
    v.abs() < 0.008
}

/// `SHT_MAX`: 32767 as f32.
pub const SHT_MAX: f32 = 32767.0;
/// `SHT_MINV`.
pub const SHT_MINV: f32 = 1.0 / SHT_MAX;

/// `xyz_t`.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Xyz {
    pub x: f32,
    pub y: f32,
    pub z: f32,
}

impl Xyz {
    pub const ZERO: Xyz = Xyz { x: 0.0, y: 0.0, z: 0.0 };

    pub const fn new(x: f32, y: f32, z: f32) -> Self {
        Self { x, y, z }
    }

    /// `xyz_t_add`.
    pub fn add(self, o: Xyz) -> Xyz {
        Xyz::new(self.x + o.x, self.y + o.y, self.z + o.z)
    }

    /// `xyz_t_sub` (`self - o`).
    pub fn sub(self, o: Xyz) -> Xyz {
        Xyz::new(self.x - o.x, self.y - o.y, self.z - o.z)
    }

    /// `xyz_t_mult_v`.
    pub fn scale(self, k: f32) -> Xyz {
        Xyz::new(self.x * k, self.y * k, self.z * k)
    }

    /// `Math3DVecLength`.
    pub fn length(self) -> f32 {
        (self.x * self.x + self.y * self.y + self.z * self.z).sqrt()
    }
}

/// `s_xyz`.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SXyz {
    pub x: i16,
    pub y: i16,
    pub z: i16,
}

