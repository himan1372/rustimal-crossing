/// libultra `sins`: sine of a u16 angle as s16 (scale 32767).
pub fn sins(x: u16) -> i16 {
    let x = x >> 4;
    let val = if x & 0x400 != 0 { SINTABLE[0x3FF - (x & 0x3FF) as usize] } else { SINTABLE[(x & 0x3FF) as usize] };
    if x & 0x800 != 0 {
        val.wrapping_neg()
    } else {
        val
    }
}

/// libultra `coss` = `sins(x + 0x4000)`.
pub fn coss(x: u16) -> i16 {
    sins(x.wrapping_add(0x4000))
}

/// `sin_s`.
pub fn sin_s(angle: i16) -> f32 {
    sins(angle as u16) as f32 * SHT_MINV
}

/// `cos_s`.
pub fn cos_s(angle: i16) -> f32 {
    coss(angle as u16) as f32 * SHT_MINV
}

/// `sinf_table(x)`: radians -> s16 via `(SHT_MAX / M_PI) * x` (single precision;
/// `M_PI` is a float literal; truncated through int to s16, so angles past pi wrap), then `sins`.
pub fn sinf_table(x: f32) -> f32 {
    let v = ((SHT_MAX / std::f32::consts::PI) * x) as i32 as i16;
    sins(v as u16) as f32 * SHT_MINV
}

/// `cosf_table(x)`.
pub fn cosf_table(x: f32) -> f32 {
    let v = ((SHT_MAX / std::f32::consts::PI) * x) as i32 as i16;
    coss(v as u16) as f32 * SHT_MINV
}

/// `U_GetAtanTable(y, x)`: atan(y/x) for 0 <= y/x <= 1.
pub fn u_get_atan_table(y: f32, x: f32) -> u16 {
    if x == 0.0 {
        return ATNTABLE[0x400];
    }
    // C: `idx = ((y/x) * 1024.0f) + 0.5f;` float -> int truncation.
    let idx = ((y / x) * 1024.0 + 0.5) as i32;
    if idx > 0x400 {
        ATNTABLE[0x400]
    } else {
        // Negative idx is unreachable from atans_table (operands are
        // pre-folded into the first octant); clamp instead of UB.
        ATNTABLE[idx.max(0) as usize]
    }
}

/// `atans_table(x, y)`: angle of the vector (x, y) where 0 points along
/// +x and 0x4000 along +y (callers pass (dz, dx) for a Y rotation).
pub fn atans_table(x: f32, y: f32) -> i16 {
    let t = |a: f32, b: f32| u_get_atan_table(a, b) as i32;
    let tbl: i32 = if y >= 0.0 {
        if x >= 0.0 {
            if x >= y {
                if y != 0.0 {
                    t(y, x)
                } else {
                    0
                }
            } else {
                0x4000 - t(x, y)
            }
        } else if -x < y {
            t(-x, y) + 0x4000
        } else {
            0x8000 - t(y, -x)
        }
    } else if x < 0.0 {
        if x <= y {
            t(-y, -x) + 0x8000
        } else {
            0xC000 - t(-x, -y)
        }
    } else if x < -y {
        t(x, -y) + 0xC000
    } else {
        -t(-y, x)
    };
    tbl as i16
}

