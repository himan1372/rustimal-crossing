#[no_mangle]
pub extern "C" fn pc_math_sins(x: u16) -> i16 {
    sins(x)
}

#[no_mangle]
pub extern "C" fn pc_math_atans_table(x: f32, y: f32) -> i16 {
    atans_table(x, y)
}

#[no_mangle]
pub extern "C" fn pc_math_check_percent_abs(x: f32, min: f32, max: f32, scale: f32, shift_by_min: i32) -> f32 {
    check_percent_abs(x, min, max, scale, shift_by_min != 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sins_quadrants() {
        assert_eq!(sins(0), 0);
        assert_eq!(sins(0x4000), SINTABLE[0x3FF]);
        assert_eq!(sins(0x8000), 0);
        assert_eq!(sins(0xC000), -SINTABLE[0x3FF]);
        assert_eq!(coss(0), SINTABLE[0x3FF]);
    }

    #[test]
    fn atans_cardinal_directions() {
        assert_eq!(atans_table(1.0, 0.0), 0);
        assert_eq!(atans_table(0.0, 1.0), 0x4000);
        assert_eq!(atans_table(-1.0, 0.0) as u16, 0x8000);
        assert_eq!(atans_table(0.0, -1.0) as u16, 0xC000);
        assert_eq!(atans_table(1.0, 1.0), 0x2000);
        assert_eq!(atans_table(1.0, -1.0) as u16, 0xE000);
    }

    #[test]
    fn chase_and_calc() {
        let mut v = 0.0;
        assert!(!chase_f(&mut v, 1.0, 0.4));
        assert!(!chase_f(&mut v, 1.0, 0.4));
        assert!(chase_f(&mut v, 1.0, 0.4));
        assert_eq!(v, 1.0);
        let mut a: i16 = 0x7F00;
        assert!(chase_angle2(&mut a, 0x7FFF, 0x200)); // crosses through wrap
        let mut a: i16 = 0;
        add_calc_short_angle2(&mut a, 0x1000, 0.5, 0x400, 0);
        assert_eq!(a, 0x400);
        assert_eq!(check_percent_abs(5.0, 9.899495, 61.0, 1.0 / 61.0, false), 0.0);
        assert_eq!(check_percent_abs(70.0, 9.899495, 61.0, 1.0 / 61.0, false), 1.0);
        assert_eq!(get_percent(10, 0, 5), 0.5);
    }
}
