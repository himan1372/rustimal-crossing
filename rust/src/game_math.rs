/// `chase_angle`: step `value` toward `target` by `step * frame_scale`
/// (`game_GameFrame_2F` = `game_GameFrameF * 0.5`). True on arrival.
pub fn chase_angle(value: &mut i16, target: i16, mut step: i16, frame_scale: f32) -> bool {
    if step != 0 {
        if value.wrapping_sub(target) > 0 {
            step = step.wrapping_neg();
        }
        *value = value.wrapping_add((step as f32 * frame_scale) as i16);
        if (value.wrapping_sub(target) as i32) * (step as i32) >= 0 {
            *value = target;
            return true;
        }
    } else if *value == target {
        return true;
    }
    false
}

/// `chase_s`.
pub fn chase_s(value: &mut i16, target: i16, mut step: i16) -> bool {
    if step != 0 {
        if *value > target {
            step = step.wrapping_neg();
        }
        *value = value.wrapping_add(step);
        if (step as i32) * (*value as i32 - target as i32) >= 0 {
            *value = target;
            return true;
        }
    } else if *value == target {
        return true;
    }
    false
}

/// `chase_f`.
pub fn chase_f(value: &mut f32, target: f32, mut step: f32) -> bool {
    if step != 0.0 {
        if *value > target {
            step = -step;
        }
        *value += step;
        if step * (*value - target) >= 0.0 {
            *value = target;
            return true;
        }
    } else if *value == target {
        return true;
    }
    false
}

/// `chase_xyz_t`: move `value` toward `target` by distance `fraction`;
/// returns the remaining distance.
pub fn chase_xyz(value: &mut Xyz, target: Xyz, fraction: f32) -> f32 {
    let diff = target.sub(*value);
    let dist = diff.length();
    if dist > fraction {
        let k = fraction / dist;
        value.x += k * diff.x;
        value.y += k * diff.y;
        value.z += k * diff.z;
        dist - fraction
    } else {
        *value = target;
        0.0
    }
}

/// `chase_angle2`: add `step` and snap to `limit` when crossing it (within
/// a quarter turn).
pub fn chase_angle2(value: &mut i16, limit: i16, step: i16) -> bool {
    let prev = *value;
    *value = value.wrapping_add(step);
    if (value.wrapping_sub(limit) as i32) * (prev.wrapping_sub(limit) as i32) <= 0
        && (value.wrapping_sub(limit) as i32).abs() < 16384
    {
        *value = limit;
        return true;
    }
    false
}

/// `inter_float`.
pub fn inter_float(value: &mut f32, target: f32, step: i32) {
    if step <= 0 {
        *value = target;
    } else {
        *value += (target - *value) / step as f32;
    }
}

/// `get_random_timer(base, range)` with `fqrand()` supplied as `r` in [0,1).
pub fn get_random_timer(base: i16, range: i16, r: f32) -> i16 {
    base.wrapping_add((range as f32 * r) as i16)
}

/// `search_position_distance`.
pub fn search_position_distance(pos: Xyz, target: Xyz) -> f32 {
    target.sub(pos).length()
}

/// `search_position_distanceXZ`.
pub fn search_position_distance_xz(pos: Xyz, target: Xyz) -> f32 {
    let dx = target.x - pos.x;
    let dz = target.z - pos.z;
    (dx * dx + dz * dz).sqrt()
}

/// `search_position_angleY`.
pub fn search_position_angle_y(pos: Xyz, target: Xyz) -> i16 {
    atans_table(target.z - pos.z, target.x - pos.x)
}

/// `search_position_angleX`.
pub fn search_position_angle_x(pos: Xyz, target: Xyz) -> i16 {
    atans_table(search_position_distance_xz(pos, target), pos.y - target.y)
}

/// Retail `add_calc`. Returns `target - value`.
pub fn add_calc(value: &mut f32, target: f32, fraction: f32, max_step: f32, min_step: f32) -> f32 {
    if *value != target {
        let mut step = fraction * (target - *value);
        if step <= -min_step || min_step <= step {
            step = step.clamp(-max_step, max_step);
            *value += step;
            if step > 0.0 {
                if *value > target {
                    *value = target;
                }
            } else if *value < target {
                *value = target;
            }
        } else if step > 0.0 {
            *value += min_step;
            if *value > target {
                *value = target;
            }
        } else {
            *value -= min_step;
            if *value < target {
                *value = target;
            }
        }
    }
    target - *value
}

/// PC-port `add_calc`: `fraction` becomes `1 - (1 - fraction)^dt` and the
/// steps scale linearly with `dt` (`mlib_calc_dt_fraction`).
pub fn add_calc_dt(value: &mut f32, target: f32, fraction: f32, max_step: f32, min_step: f32, dt: f32) -> f32 {
    let f = if fraction <= 0.0 {
        0.0
    } else if fraction >= 1.0 {
        1.0
    } else {
        1.0 - (1.0 - fraction).powf(dt)
    };
    add_calc(value, target, f, max_step * dt, min_step * dt)
}

/// `add_calc2`.
pub fn add_calc2(value: &mut f32, target: f32, fraction: f32, max_step: f32) {
    if *value != target {
        let step = (fraction * (target - *value)).clamp(-max_step, max_step);
        *value += step;
    }
}

/// `add_calc0`: decay toward zero.
pub fn add_calc0(value: &mut f32, fraction: f32, max_step: f32) {
    let step = (*value * fraction).clamp(-max_step, max_step);
    *value -= step;
}

/// `add_calc_short_angle2`: shortest-direction eased angle approach.
pub fn add_calc_short_angle2(value: &mut i16, target: i16, fraction: f32, max_step: i16, min_step: i16) -> i16 {
    let diff = target.wrapping_sub(*value);
    if *value != target {
        let mut step = (diff as f32 * fraction) as i16;
        if step > min_step || step < min_step.wrapping_neg() {
            if step > max_step {
                step = max_step;
            } else if step < max_step.wrapping_neg() {
                step = max_step.wrapping_neg();
            }
            *value = value.wrapping_add(step);
            if step > 0 {
                if target.wrapping_sub(*value) < 0 {
                    *value = target;
                }
            } else if target.wrapping_sub(*value) > 0 {
                *value = target;
            }
        } else if diff >= 0 {
            *value = value.wrapping_add(min_step);
            if target.wrapping_sub(*value) < 0 {
                *value = target;
            }
        } else {
            *value = value.wrapping_sub(min_step);
            if target.wrapping_sub(*value) > 0 {
                *value = target;
            }
        }
    }
    target.wrapping_sub(*value)
}

/// `add_calc_short_angle3`: always turns in the positive direction.
pub fn add_calc_short_angle3(value: &mut i16, target: i16, fraction: f32, max_step: i16, min_step: i16) -> i16 {
    if target != *value {
        let u_value = *value as u16 as i32;
        let mut u_target = target as u16 as i32;
        if u_value > u_target {
            u_target += 65536;
        }
        let mut step = (u_target - u_value) as f32 * fraction;
        if step > max_step as f32 {
            step = max_step as f32;
        } else if step < min_step as f32 {
            step = min_step as f32;
        }
        let new_value = (u_value + step as i32).min(u_target);
        *value = new_value as i16;
    }
    target.wrapping_sub(*value)
}

/// `check_percent_abs`: stick-style dead zone + saturation.
pub fn check_percent_abs(x: f32, min: f32, max: f32, scale: f32, shift_by_min: bool) -> f32 {
    if -min <= x && x <= min {
        return 0.0;
    }
    if x >= max {
        return 1.0;
    }
    if x <= -max {
        return -1.0;
    }
    if shift_by_min {
        if x > 0.0 {
            (x - min) * scale
        } else {
            (x + min) * scale
        }
    } else {
        x * scale
    }
}

/// `get_percent_forAccelBrake`.
pub fn percent_accel_brake(now: f32, start: f32, end: f32, accel: f32, brake: f32) -> f32 {
    if now >= end {
        return 1.0;
    }
    if now <= start {
        return 0.0;
    }
    let total = end - start;
    let cur = now - start;
    if total < accel + brake {
        return 0.0;
    }
    let step = 1.0 / ((2.0 * total - accel) - brake);
    let mut percent;
    if accel != 0.0 {
        if cur <= accel {
            return cur * (step * cur) / accel;
        }
        percent = step * accel;
    } else {
        percent = 0.0;
    }
    if cur <= total - brake {
        return percent + (step * 2.0) * (cur - accel);
    }
    percent += 2.0 * step * ((total - accel) - brake);
    if brake != 0.0 {
        percent += step * brake;
        if cur < total {
            let diff = total - cur;
            percent -= step * diff * diff / brake;
        }
    }
    percent
}

/// `get_percent(max, min, x)`: clamped linear ratio.
pub fn get_percent(max: i32, min: i32, x: i32) -> f32 {
    let mut percent = 1.0;
    if x < min {
        percent = 0.0;
    } else if x < max {
        let total = (max - min) as f32;
        if total != 0.0 {
            percent = ((x - min) as f32 / total).min(1.0);
        }
    }
    percent
}

