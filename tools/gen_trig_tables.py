# Generates rust/src/game_math_tables.rs from the decomp's lookup tables.
# Usage: python -I tools/gen_trig_tables.py <decomp-root> > rust/src/game_math_tables.rs
#   <decomp-root>/src/static/libultra/gu/sins.c   -> SINTABLE (0x400 x s16)
#   <decomp-root>/src/system/sys_math_atan.c      -> ATNTABLE (0x401 x u16)
import os
import re
import sys

root = sys.argv[1]


def table(path, name):
    txt = open(path, encoding="utf-8", errors="replace").read()
    body = re.search(name + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", txt, re.S).group(1)
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S)
    return [int(v, 0) for v in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", body)]


sin = table(os.path.join(root, "src/static/libultra/gu/sins.c"), "sintable")
atn = table(os.path.join(root, "src/system/sys_math_atan.c"), "atntable")
assert len(sin) == 0x400, len(sin)
assert len(atn) == 0x401, len(atn)


def emit(name, ty, vals, fmt):
    print(f"pub const {name}: [{ty}; {len(vals)}] = [")
    for i in range(0, len(vals), 12):
        print("    " + ", ".join(fmt(v) for v in vals[i : i + 12]) + ",")
    print("];")


print("//! Lookup tables for `game_math` (generated by tools/gen_trig_tables.py; do not hand-edit).")
print("//! Sources: libultra `src/static/libultra/gu/sins.c` (`sintable`) and")
print("//! `src/system/sys_math_atan.c` (`atntable`).")
print()
print("/// libultra quarter-wave sine table: `sins` reads it with `x >> 4`.")
emit("SINTABLE", "i16", [v if v < 0x8000 else v - 0x10000 for v in sin], lambda v: f"{v}")
print()
print("/// `atntable`: atan(i/1024) in s16 angle units for i in 0..=1024.")
emit("ATNTABLE", "u16", atn, lambda v: f"0x{v:04X}")
