# Generates the data tables at the bottom of rust/src/event_map_npc.rs.
# Usage: python tools/gen_evmn.py <decomp>/src/game/m_event_map_npc_data.c_inc
#            <decomp>/include/m_name_table.h <decomp>/include/m_random_field_h.h
# then rename mRF_BLOCKKIND_* -> BLOCKKIND_*.
import re, sys
src, nametab, rfh = sys.argv[1], sys.argv[2], sys.argv[3]
txt = open(src, encoding='utf-8').read().replace('\r','')
defs = {}
for f in (nametab, rfh):
    for line in open(f, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*#define\s+(\w+)\s+(.+?)\s*(//.*)?$', line)
        if m and '(' not in m.group(1): defs[m.group(1)] = m.group(2)
def ev(n, depth=0):
    e = defs[n]
    e = re.sub(r'\b([A-Za-z_]\w*)\b', lambda m: str(ev(m.group(1), depth+1)), e)
    return eval(e.replace('<<','<<'))
names = re.findall(r'static mActor_name_t (\w+)\[\] = \{(.*?)\};', txt, re.S)
poss  = re.findall(r'static mEvMN_actor_pos_c (\w+)\[\] = \{(.*?)\};', txt, re.S)
infos = re.findall(r'static mEvMN_actor_info_c (\w+) = \{ (\w+), (\w+) \};', txt)
tabs  = re.findall(r'static mEvMN_actor_info_c\* (\w+)\[\] = \{(.*?)\};', txt, re.S)
npcs  = re.findall(r'static mEvMN_npc_data_c (\w+) = \{ (0b[01]+), (\w+) \};', txt)
datas = re.findall(r'static mEvMN_data_c (\w+) = \{ (\d+), (\d+), (\d+), (\d+), (\w+), &(\w+), (\w+) \};', txt)
master = re.search(r'l_event_set_table\[\] = \{(.*?)\};', txt, re.S).group(1)
used = set()
out = []
U = lambda s: s.upper()
for n, body in names:
    ids = [x.strip() for x in body.split(',') if x.strip()]
    used.update(ids)
    out.append(f"const {U(n)}: [u16; {len(ids)}] = [{', '.join(ids)}];")
for n, body in poss:
    ps = re.findall(r'\{\s*(\d+),\s*(\d+)\s*\}', re.sub(r'//.*','',body))
    out.append(f"const {U(n)}: [ActorPos; {len(ps)}] = [{', '.join(f'ActorPos::new({a}, {b})' for a,b in ps)}];")
for n, a, p in infos:
    out.append(f"const {U(n)}: ActorInfo = ActorInfo {{ names: &{U(a)}, positions: &{U(p)} }};")
for n, body in tabs:
    ids = [x.strip().lstrip('&') for x in body.split(',') if x.strip()]
    out.append(f"const {U(n)}: [&ActorInfo; {len(ids)}] = [{', '.join('&'+U(i) for i in ids)}];")
for n, flags, cloth in npcs:
    used.add(cloth)
    out.append(f"const {U(n)}: NpcData = NpcData {{ are_npc_flags: {flags}, cloth: {cloth} }};")
for n, t, nm, mm, nx, tab, npc, bk in datas:
    used.add(bk)
    out.append(f"const {U(n)}: EventMapData = EventMapData {{ get_npc_idx_type: {t}, normal_npc_max: {nm}, map_max: {mm}, npc_max: {nx}, actor_info: &{U(tab)}, npc_data: &{U(npc)}, block_kind: {bk} }};")
ms = [x.strip() for x in re.sub(r'//.*','',master).split(',') if x.strip()]
out.append(f"/// `l_event_set_table`, indexed by `mEvMN_TYPE_*`.\npub const EVENT_SET_TABLE: [Option<&EventMapData>; {len(ms)}] = [{', '.join('None' if x=='NULL' else 'Some(&'+U(x.lstrip('&'))+')' for x in ms)}];")
consts = []
for n in sorted(used):
    v = ev(n)
    consts.append(f"pub const {n}: u{'32' if n.startswith('mRF_') else '16'} = 0x{v:04X}; // {defs[n]}")
print("// ---- generated by gen_evmn.py from src/game/m_event_map_npc_data.c_inc ----")
print("\n".join(consts)); print(); print("\n".join(out))
