# Generates rust/src/room_scoring_tables.rs (feng shui + Happy Room Academy data).
#
# Usage (MSYS2 shell, mingw32 gcc on PATH):
#   python -I tools/gen_room_scoring_tables.py <decomp-root> <scratch-dir> > rust/src/room_scoring_tables.rs
#
# The C initializers are compiled with gcc so every enum name resolves exactly as
# the game sees it; nothing is hand-copied. Sources (byte-identical in ac-decomp
# and ACGC-PC-Port):
#   src/game/m_huusui_room_ovl_data.inc   mMkRm_ftr_info (feng shui: type, has_face)
#   src/game/m_mark_room_ovl.c            mMkRm_series_info, mMkRm_ftr_info (HRA),
#                                         mMkRm_wall_from, mMkRm_floor_from
#   include/m_mark_room.h, m_room_type.h, m_huusui_room.h,
#   include/m_name_table_{floor,wall}_decl.h
import os
import re
import subprocess
import sys

root, scratch = sys.argv[1], sys.argv[2]
inc = os.path.join(root, "include")
src = os.path.join(root, "src", "game")


def read(p):
    return open(p, encoding="utf-8", errors="replace").read().replace("\r", "")


def enums(txt):
    return "\n".join(re.findall(r"enum(?:\s+\w+)?\s*\{.*?\};", txt, re.S))


def defines(txt):
    # Only the #define lines (skip include guards) so the decomp's types.h stays out.
    lines = [l for l in txt.split("\n") if l.startswith("#define ")]
    return "\n".join(l for l in lines if not l.split()[1].endswith("_H"))


def array_body(txt, name):
    m = re.search(r"\b" + name + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\n\};", txt, re.S)
    return m.group(1)


mark_c = read(os.path.join(src, "m_mark_room_ovl.c"))
harness = f"""
#include <stdio.h>
#define TRUE 1
#define FALSE 0
#define BUGFIXES_OFF 1
{enums(read(os.path.join(inc, "m_mark_room.h")))}
{enums(read(os.path.join(inc, "m_room_type.h")))}
{enums(read(os.path.join(inc, "m_huusui_room.h")))}
{defines(read(os.path.join(inc, "m_name_table_floor_decl.h")))}
{defines(read(os.path.join(inc, "m_name_table_wall_decl.h")))}
#define FTR_NUM 1266
#define WALL_NUM 67
#define CARPET_NUM 67
typedef struct {{ int series, group_idx, has_face, is_lucky, birth_type, surface_type; }} mk_t;
typedef struct {{ int type, num_ftr, wall_floor_idx; }} series_t;
typedef struct {{ int huusui_type, has_face; }} hs_t;
static series_t series_info[] = {{ {array_body(mark_c, "mMkRm_series_info")}
}};
static mk_t mk_info[FTR_NUM] = {{ {array_body(mark_c, "mMkRm_ftr_info")}
}};
static int wall_from[WALL_NUM] = {{ {array_body(mark_c, "mMkRm_wall_from")}
}};
static int floor_from[CARPET_NUM] = {{ {array_body(mark_c, "mMkRm_floor_from")}
}};
static hs_t hs_info[FTR_NUM] = {{
#include "m_huusui_room_ovl_data.inc"
}};
int main(void) {{
  int i;
  printf("SERIES %d\\n", (int)(sizeof(series_info) / sizeof(series_info[0])));
  for (i = 0; i < (int)(sizeof(series_info) / sizeof(series_info[0])); i++)
    printf("S %d %d\\n", series_info[i].type, series_info[i].wall_floor_idx);
  for (i = 0; i < FTR_NUM; i++)
    printf("M %d %d %d %d %d %d\\n", mk_info[i].series, mk_info[i].group_idx, mk_info[i].has_face,
           mk_info[i].is_lucky, mk_info[i].birth_type, mk_info[i].surface_type);
  for (i = 0; i < FTR_NUM; i++) printf("H %d %d\\n", hs_info[i].huusui_type, hs_info[i].has_face);
  for (i = 0; i < WALL_NUM; i++) printf("W %d\\n", wall_from[i]);
  for (i = 0; i < CARPET_NUM; i++) printf("F %d\\n", floor_from[i]);
  printf("O %d %d %d %d\\n", FLOOR_MY_ORIG_START, FLOOR_MY_ORIG_END, WALL_MY_ORIG_START, WALL_MY_ORIG_END);
  return 0;
}}
"""
os.makedirs(scratch, exist_ok=True)
c_path = os.path.join(scratch, "room_scoring_harness.c")
exe = os.path.join(scratch, "room_scoring_harness.exe")
open(c_path, "w", encoding="utf-8").write(harness)
subprocess.run(["gcc", "-w", "-I", inc, "-I", src, "-o", exe, c_path], check=True)
out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split("\n")

series, mk, hs, wall, floor, orig = [], [], [], [], [], None
for line in out:
    p = line.split()
    if not p:
        continue
    if p[0] == "S":
        series.append((int(p[1]), int(p[2])))
    elif p[0] == "M":
        mk.append(tuple(int(v) for v in p[1:]))
    elif p[0] == "H":
        hs.append((int(p[1]), int(p[2])))
    elif p[0] == "W":
        wall.append(int(p[1]))
    elif p[0] == "F":
        floor.append(int(p[1]))
    elif p[0] == "O":
        orig = [int(v) for v in p[1:]]
assert len(series) == 60 and len(mk) == 1266 and len(hs) == 1266 and len(wall) == 67 and len(floor) == 67


def rows(vals, per=16):
    for i in range(0, len(vals), per):
        print("    " + ", ".join(vals[i : i + per]) + ",")


print("//! Room scoring data (generated by tools/gen_room_scoring_tables.py; do not hand-edit).")
print("//! Feng shui: `m_huusui_room_ovl_data.inc`; HRA: `m_mark_room_ovl.c` tables.")
print()
print(f"pub const FLOOR_MY_ORIG_START: u8 = {orig[0]};")
print(f"pub const FLOOR_MY_ORIG_END: u8 = {orig[1]};")
print(f"pub const WALL_MY_ORIG_START: u8 = {orig[2]};")
print(f"pub const WALL_MY_ORIG_END: u8 = {orig[3]};")
print()
print("/// Feng shui per furniture index: `huusui_type | (has_face << 4)`.")
print(f"pub const HUUSUI_FTR_INFO: [u8; {len(hs)}] = [")
rows([f"0x{t | (f << 4):02X}" for t, f in hs])
print("];")
print()
print("/// `mMkRm_series_info`: (series type, wall/floor index). `num_ftr` is computed at runtime.")
print(f"pub const MKRM_SERIES_INFO: [(u8, u8); {len(series)}] = [")
rows([f"({t}, {w})" for t, w in series], 8)
print("];")
print()
print("/// HRA per furniture index, packed: series | group_idx << 6 | has_face << 16 |")
print("/// is_lucky << 17 | birth_type << 18 | surface_type << 24.")
print(f"pub const MKRM_FTR_INFO: [u32; {len(mk)}] = [")
rows([f"0x{s | (g << 6) | (fa << 16) | (lu << 17) | (b << 18) | (su << 24):07X}" for s, g, fa, lu, b, su in mk], 8)
print("];")
print()
print("/// `mMkRm_wall_from`: birth type of each wallpaper.")
print(f"pub const MKRM_WALL_FROM: [u8; {len(wall)}] = [")
rows([str(v) for v in wall])
print("];")
print()
print("/// `mMkRm_floor_from`: birth type of each carpet.")
print(f"pub const MKRM_FLOOR_FROM: [u8; {len(floor)}] = [")
rows([str(v) for v in floor])
print("];")
