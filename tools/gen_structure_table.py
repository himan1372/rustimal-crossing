# Generates the STRUCTURE_SETUP table for rust/src/buildings.rs from
# src/actor/ac_structure_clip.c_inc (aSTR_setupActor_proc's setupInfo_table).
# Enum values (mAc_PROFILE_*, aSTR_TYPE_*, aSTR_PAL_*) are resolved by compiling
# the enums from include/m_actor.h and include/ac_structure.h with gcc.
# Usage: python -I tools/gen_structure_table.py <decomp-root> <scratch-dir>
import os
import re
import subprocess
import sys

root, scratch = sys.argv[1], sys.argv[2]


def read(p):
    return open(p, encoding="utf-8", errors="replace").read().replace("\r", "")


clip = read(os.path.join(root, "src/actor/ac_structure_clip.c_inc"))
body = re.search(r"setupInfo_table\[\] = \{(.*?)\n    \};", clip, re.S).group(1)
rows = re.findall(r"\{\s*(mAc_PROFILE_\w+),\s*(aSTR_TYPE_\w+),\s*(aSTR_PAL_\w+),\s*0\s*\}", body)

actor_h = read(os.path.join(root, "include/m_actor.h"))
lines = actor_h.split("\n")
start = next(i for i, l in enumerate(lines) if "mAc_PROFILE_PLAYER" in l)
end = next(i for i, l in enumerate(lines) if "mAc_PROFILE_NUM" in l)
profile_enum = "enum {\n" + "\n".join(lines[start : end + 1]) + "\n};"
str_h = read(os.path.join(root, "include/ac_structure.h"))
str_enums = "\n".join(e for e in re.findall(r"enum(?:\s+\w+)?\s*\{.*?\};", str_h, re.S) if "aSTR_TYPE_" in e or "aSTR_PAL_" in e)

prog = "#include <stdio.h>\n" + profile_enum + "\n" + str_enums + "\nint main(void){\n"
for p, t, c in rows:
    prog += f'printf("%d %d %d\\n", {p}, {t}, {c});\n'
prog += "return 0;}\n"
os.makedirs(scratch, exist_ok=True)
c_path = os.path.join(scratch, "structure_table.c")
exe = os.path.join(scratch, "structure_table.exe")
open(c_path, "w", encoding="utf-8").write(prog)
subprocess.run(["gcc", "-w", "-o", exe, c_path], check=True)
vals = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split("\n")

print(f"/// `setupInfo_table` (index = structure FG id - STRUCTURE_START):")
print("/// (profile id, aSTR_TYPE, aSTR_PAL). Generated by tools/gen_structure_table.py.")
print(f"pub const STRUCTURE_SETUP: [(i16, i16, i16); {len(rows)}] = [")
for (p, t, c), v in zip(rows, vals):
    a, b, d = v.split()
    print(f"    ({a}, {b}, {d}), // {p[len('mAc_PROFILE_'):]} / {t[len('aSTR_TYPE_'):]} / {c[len('aSTR_PAL_'):]}")
print("];")
